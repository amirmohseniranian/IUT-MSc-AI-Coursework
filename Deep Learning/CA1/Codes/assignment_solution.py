    x1, x2 = X[:, 0], X[:, 1]
    targets = np.empty(len(X), dtype=int)
    targets[x2 < 0] = 1
    targets[(x2 > 0) & (x1 < 0)] = 2
    targets[(x2 > 0) & (x1 > 0)] = 3
    if np.any(x1 == 0) or np.any(x2 == 0):
        raise ValueError("The supplied quadrant data contain an axis sample; class rules need an explicit tie rule.")
    return targets

